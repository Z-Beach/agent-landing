#!/usr/bin/env python3
"""
build_static_site.py - generate a self-contained static mirror of the
Agent Landing site into docs/ so it can be served by GitHub Pages
(or opened straight off disk) without the Pi, the tunnel, or any Python.

The live site on the Pi answers /api/* dynamically. This script snapshots
those endpoints into plain JSON files and rewrites every absolute link in
landing/index.html to a relative path, so the mirror works at any base URL.

Usage:
    python tools/build_static_site.py [--live https://host]
"""
import argparse
import json
import os
import re
import shutil
import time
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_LANDING = os.path.join(ROOT, "landing")
SRC_PROJECTS = os.path.join(ROOT, "projects")
SRC_PASSPORTS = os.path.join(ROOT, "agent-passports")
DEST = os.path.join(ROOT, "docs")

TEXT_EXTS = {".md", ".py", ".ail", ".ebnf", ".json", ".txt", ".html", ".css", ".js"}


def reset_dest():
    if os.path.isdir(DEST):
        shutil.rmtree(DEST)
    os.makedirs(DEST)


def copy_static():
    for name in sorted(os.listdir(SRC_LANDING)):
        src = os.path.join(SRC_LANDING, name)
        if os.path.isfile(src):
            shutil.copy2(src, os.path.join(DEST, name))
    # Also copy tunnel-url.txt and onion-address.txt from repo root if they exist
    for fname in ("tunnel-url.txt", "onion-address.txt"):
        src_path = os.path.join(ROOT, fname)
        if os.path.isfile(src_path):
            shutil.copy2(src_path, os.path.join(DEST, fname))


def copy_projects():
    """Copy project content so /projects/... resolves on the mirror."""
    if not os.path.isdir(SRC_PROJECTS):
        return
    dest = os.path.join(DEST, "projects")
    os.makedirs(dest, exist_ok=True)
    for name in sorted(os.listdir(SRC_PROJECTS)):
        src = os.path.join(SRC_PROJECTS, name)
        if os.path.isdir(src) and name != "__pycache__":
            shutil.copytree(src, os.path.join(dest, name), dirs_exist_ok=True,
                            ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".git"))
        elif os.path.isfile(src):
            shutil.copy2(src, os.path.join(dest, name))


def read_description(pdir):
    readme = os.path.join(pdir, "README.md")
    if not os.path.exists(readme):
        return ""
    try:
        with open(readme, encoding="utf-8", errors="replace") as f:
            for line in f:
                s = line.strip()
                if s and not s.startswith("#"):
                    return s[:200]
    except OSError:
        pass
    return ""


def count_files(pdir):
    return sum(len(files) for _, _, files in os.walk(pdir))


def write_json(rel_path, data):
    path = os.path.join(DEST, rel_path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


def build_projects_api():
    projects = []
    if os.path.isdir(SRC_PROJECTS):
        for name in sorted(os.listdir(SRC_PROJECTS)):
            pdir = os.path.join(SRC_PROJECTS, name)
            if not os.path.isdir(pdir) or name == "__pycache__":
                continue
            projects.append({
                "name": name,
                "description": read_description(pdir),
                "file_count": count_files(pdir),
                "url": "api/projects/%s/index.json" % name,
                "browse": "projects/%s/" % name,
            })
    write_json("api/projects/index.json",
               {"projects": projects, "count": len(projects),
                "note": "Static snapshot. Generated by tools/build_static_site.py."})

    for proj in projects:
        name = proj["name"]
        pdir = os.path.join(SRC_PROJECTS, name)
        entries = []
        for entry in sorted(os.listdir(pdir)):
            fpath = os.path.join(pdir, entry)
            if os.path.isdir(fpath):
                entries.append({"name": entry, "type": "dir"})
            else:
                entries.append({"name": entry, "type": "file",
                                "size": os.path.getsize(fpath)})
        write_json("api/projects/%s/index.json" % name,
                   {"path": name, "entries": entries, "browse": "../../../projects/%s/" % name})


def build_passport_api():
    if not os.path.isdir(SRC_PASSPORTS):
        return
    for agent_id in sorted(os.listdir(SRC_PASSPORTS)):
        adir = os.path.join(SRC_PASSPORTS, agent_id)
        identity = os.path.join(adir, "identity.json")
        if not os.path.isfile(identity):
            continue
        try:
            with open(identity, encoding="utf-8", errors="replace") as f:
                data = json.load(f)
        except (OSError, json.JSONDecodeError):
            continue
        data.setdefault("agent_id", agent_id)
        write_json("api/passport/%s/index.json" % agent_id, data)


def build_checkins_api(live):
    data = []
    if live:
        url = live.rstrip("/") + "/api/checkins"
        try:
            with urllib.request.urlopen(url, timeout=10) as r:
                loaded = json.loads(r.read().decode("utf-8", "replace"))
                if isinstance(loaded, list):
                    data = loaded
                    print("checkins: pulled %d from live site" % len(data))
        except Exception as exc:  # noqa: BLE001 - snapshot is best effort
            print("checkins: live fetch failed (%s); writing empty snapshot" % exc)
    write_json("api/checkins.json", data)


def build_chat_api(live):
    data = {"messages": [], "count": 0}
    if live:
        url = live.rstrip("/") + "/api/chat"
        try:
            with urllib.request.urlopen(url, timeout=10) as r:
                loaded = json.loads(r.read().decode("utf-8", "replace"))
                if isinstance(loaded, dict) and isinstance(loaded.get("messages"), list):
                    data = loaded
                    print("chat: pulled %d messages from live site" % len(data["messages"]))
        except Exception as exc:  # noqa: BLE001 - snapshot is best effort
            print("chat: live fetch failed (%s); writing empty snapshot" % exc)
    data["note"] = ("Static snapshot. Posting only works on the live site, "
                    "not on this mirror.")
    write_json("api/chat.json", data)


LINK_REWRITES = [
    ('href="/api/projects/README.md"', 'href="projects/README.md"'),
    ('href="/api/projects"', 'href="api/projects/index.json"'),
    ('href="/stray-agent-catch-design.md"', 'href="stray-agent-catch-design.md"'),
    ('fetch(\'/api/checkins\')', 'fetch(\'api/checkins.json\')'),
    ('fetch("/api/checkins")', 'fetch("api/checkins.json")'),
    ("fetch('/api/chat')", "fetch('api/chat.json')"),
    # the mirror cannot accept chat posts - fail with a readable message
    ("  fetch('/api/chat', {\n    method: 'POST',",
     "  if (window.MIRROR_READONLY) {\n"
     "    alert('This is the static mirror. Chat posting works only on the "
     "live site; see the note at the bottom of the page.');\n"
     "    return;\n"
     "  }\n"
     "  fetch('/api/chat', {\n    method: 'POST',"),
]

# /api/projects/<name> and /api/passport/<id> become snapshot JSON files
API_LINK_RE = re.compile(r'href="/api/(projects|passport)/([A-Za-z0-9._-]+)"')
API_LINK_SUB = r'href="api/\1/\2/index.json"'

MIRROR_NOTE = (
    '<p style="color:#666; font-size:12px; border-top:1px solid #333; '
    'padding-top:8px; margin-top:12px;">Static mirror of the live site. '
    'API responses under <code>api/</code> are snapshots, not live endpoints. '
    'Chat is read-only here. The live copy runs on a Raspberry Pi. '
    'Source: '
    '<a href="https://github.com/Z-Beach/agent-landing" style="color:#666;">'
    'github.com/Z-Beach/agent-landing</a></p>\n'
    '<p id="live-pi-link" style="color:#ffaa00; font-size:12px; margin-top:4px;">'
    'Live Pi: resolving current tunnel URL...</p>\n'
    '<p id="onion-link" style="color:#ffaa00; font-size:12px; margin-top:4px;">'
    'Tor (permanent): resolving...</p>\n'
    '<script>\n'
    'window.MIRROR_READONLY = true;\n'
    '(function() {\n'
    '  fetch("tunnel-url.txt").then(r => r.text()).then(t => {\n'
    '    var m = t.match(/https:\\/\\/[a-z0-9-]+\\.trycloudflare\\.com/);\n'
    '    var el = document.getElementById("live-pi-link");\n'
    '    if (m && el) {\n'
    '      el.innerHTML = \'Live Pi (tunnel): <a href="\' + m[0] + \'" style="color:#ffaa00;">\' + m[0] + \'</a>\';\n'
    '    } else if (el) {\n'
    '      el.textContent = "Live Pi: tunnel URL not yet published.";\n'
    '    }\n'
    '  }).catch(function() {\n'
    '    var el = document.getElementById("live-pi-link");\n'
    '    if (el) el.textContent = "Live Pi: could not resolve tunnel URL.";\n'
    '  });\n'
    '  fetch("onion-address.txt").then(r => r.text()).then(t => {\n'
    '    var m = t.match(/[a-z2-7]{56}\\.onion/);\n'
    '    var el = document.getElementById("onion-link");\n'
    '    if (m && el) {\n'
    '      el.innerHTML = \'Tor (permanent): <a href="http://\' + m[0] + \'" style="color:#ffaa00;">\' + m[0] + \'</a> (requires Tor)\';\n'
    '    } else if (el) {\n'
    '      el.textContent = "Tor: address not yet published.";\n'
    '    }\n'
    '  }).catch(function() {\n'
    '    var el = document.getElementById("onion-link");\n'
    '    if (el) el.textContent = "Tor: could not resolve address.";\n'
    '  });\n'
    '})();\n'
    '</script>\n'
)


def rewrite_index():
    src = os.path.join(SRC_LANDING, "index.html")
    with open(src, encoding="utf-8", errors="replace") as f:
        html = f.read()

    for old, new in LINK_REWRITES:
        html = html.replace(old, new)

    html = API_LINK_RE.sub(API_LINK_SUB, html)

    # insert mirror note before the closing of the philosophy/footer block
    marker = "</body>"
    if marker in html:
        html = html.replace(marker, MIRROR_NOTE + marker, 1)

    with open(os.path.join(DEST, "index.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(html)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--live", default="", help="live site base URL for checkin snapshot")
    args = ap.parse_args()

    reset_dest()
    copy_static()
    copy_projects()
    build_projects_api()
    build_passport_api()
    build_checkins_api(args.live)
    build_chat_api(args.live)
    rewrite_index()

    # GitHub Pages: stop Jekyll from touching generated files
    with open(os.path.join(DEST, ".nojekyll"), "w", encoding="utf-8") as f:
        f.write("")

    stamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    write_json("api/meta.json", {"built_at": stamp, "source": "tools/build_static_site.py"})
    print("built docs/ at %s" % stamp)


if __name__ == "__main__":
    main()
