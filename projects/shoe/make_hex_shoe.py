"""Generate shoe_hex_10p5_7E.scad: hollow upper + hex-carved side walls.

Layout (final coords, mm):
  - sole solid below z = SOLE_Z (12); never cut.
  - cavity comes from cavity.stl (make_cavity.py): foot outline + 3mm
    clearance, roof follows the shell eroded 4mm, open through the top
    for y < 190 (entry), closed roof from y = 190 (instep bridge + toe box).
  - hex windows: pointy-top hex prisms along X, z in [14, top(y)-8],
    y in [35, 248] (heel counter and toe cap stay solid).
"""
import numpy as np
import os
from scale_to_size import SOLE_Z, OUT

ROOF_WALL = 4.0       # material kept above cavity
COLLAR_RIM = 6.0      # solid rim kept below the top edge
HEX_R = 5.2           # circumradius -> ~9mm across flats
HEX_PITCH_Y = 11.5    # hole 9 + strut 2.5
HEX_ROW_DZ = 9.96     # 11.5 * sin(60)
OPEN_Y = 110.0        # (legacy) cavity open up to here
BRIDGE_Y = 190.0      # closed from here (instep bridge + toe box)
KEEP_HEEL_Y = 30.0    # heel counter stays solid
KEEP_TOE_Y = 250.0    # toe cap stays solid
SOLE_CUT_Z = 13.5     # hex cutter starts just above the 12mm sole


def load_roof():
    t = np.loadtxt(os.path.join(OUT, "roof_table.txt"))
    return t[:, 0], t[:, 1]


def roof_at(y):
    return float(np.interp(y, ROOF_Y, ROOF_Z))


def cavity_stations():
    return []  # cavity now comes from cavity.stl (see make_cavity.py)


def hex_holes():
    """Centers of fully-contained hex holes, tested against all keep-outs."""
    holes = []
    z = SOLE_CUT_Z + HEX_R
    row = 0
    while z < 90.0:
        yoff = (row % 2) * HEX_PITCH_Y / 2.0
        y = KEEP_HEEL_Y + HEX_R * 0.866
        while y <= KEEP_TOE_Y - HEX_R * 0.866:
            ok = True
            for phi in (30, 90, 150, 210, 270, 330):
                a = np.radians(phi)
                vy = y + HEX_R * np.cos(a)
                vz = z + HEX_R * np.sin(a)
                if vy < KEEP_HEEL_Y or vy > KEEP_TOE_Y:
                    ok = False
                    break
                if vz < SOLE_CUT_Z or vz > roof_at(vy) - COLLAR_RIM:
                    ok = False
                    break
            if ok:
                holes.append([round(y, 2), round(z, 2)])
            y += HEX_PITCH_Y
        z += HEX_ROW_DZ
        row += 1
    return holes


def scad_data(name, rows):
    body = ",\n  ".join("[" + ", ".join(f"{v:g}" for v in r) + "]" for r in rows)
    return f"{name} = [\n  {body}\n];\n"


def main():
    holes = hex_holes()
    top_rows = [[round(y, 2), round(z, 2)] for y, z in zip(ROOF_Y, ROOF_Z)]

    src = f"""// Auto-generated by make_hex_shoe.py - edit the python, not this file.
// US men's 10.5 7E print-ready shoe: solid sole, hollow upper,
// hex-grid side walls (heel counter + toe cap solid).
// Requires cavity.stl (make_cavity.py) next to this file.
// Render: openscad -o shoe_hex_10p5_7E.stl shoe_hex_10p5_7E.scad

SOLE_Z = {SOLE_Z:g};
PART = "shoe"; // "shoe" | "cavity" | "hex"

{scad_data("TOP", top_rows)}
{scad_data("HOLES", holes)}
HEX_R = {HEX_R:g};

function top_at(y) = lookup(y, TOP);

module cavity() {{ import("cavity.stl"); }}

module hex_cut() {{
    for (h = HOLES)
        translate([0, h[0], h[1]])
            rotate([0, 90, 0])
                cylinder(h=220, r=HEX_R, $fn=6, center=true);
}}

if (PART == "cavity") cavity();
else if (PART == "hex") hex_cut();
else difference() {{
    import("baseline_10p5_7E.stl");
    cavity();
    hex_cut();
}}
"""
    path = os.path.join(OUT, "shoe_hex_10p5_7E.scad")
    with open(path, "w") as f:
        f.write(src)
    print(f"wrote {path}")
    print(f"  hex holes: {len(holes)}")


if __name__ == "__main__":
    ROOF_Y, ROOF_Z = load_roof()
    main()
else:
    ROOF_Y, ROOF_Z = load_roof()
